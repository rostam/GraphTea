package graphtea.ui.components.gsidebar;

import graphtea.ui.components.gbody.GBody;

import javax.swing.BorderFactory;
import javax.swing.BoxLayout;
import javax.swing.JButton;
import javax.swing.JLabel;
import javax.swing.JPanel;
import javax.swing.UIManager;
import java.awt.BorderLayout;
import java.awt.Color;
import java.awt.Component;
import java.awt.Dimension;
import java.awt.Font;

/**
 * A sidebar panel: a title row with a close button above the panel's content.
 *
 * <p>The title row was an 18-pixel strip in saturated orange with an etched border and a
 * lower-case "x", generated by a form designer; it now matches the rest of the window.
 *
 * @author azin azadi
 */
public class GSideBarPanel extends JPanel {
    private final GBody body;
    private final JLabel title = new JLabel();

    /** Holds the panel's content. */
    public final JPanel jPanel2 = new JPanel();

    /**
     * @param gBody     the body the sidebar belongs to
     * @param leftPanel the panel's content
     * @param label     the panel's title
     */
    public GSideBarPanel(GBody gBody, Component leftPanel, String label) {
        this.body = gBody;
        setLayout(new BorderLayout());
        add(buildHeader(), BorderLayout.NORTH);
        jPanel2.setLayout(new BoxLayout(jPanel2, BoxLayout.X_AXIS));
        jPanel2.add(leftPanel);
        add(jPanel2, BorderLayout.CENTER);
        setTitle(label);
    }

    private JPanel buildHeader() {
        title.setFont(title.getFont().deriveFont(Font.BOLD));

        JButton close = new JButton("×");
        close.setToolTipText("Close this panel");
        close.setFocusable(false);
        close.setMargin(new java.awt.Insets(0, 6, 0, 6));
        // FlatLaf draws a toolbar-style button: flat until hovered.
        close.putClientProperty("JButton.buttonType", "toolBarButton");
        close.addActionListener(e -> body.hideSideBar(jPanel2.getComponent(0), title.getText()));

        Color rule = UIManager.getColor("Separator.foreground");
        JPanel header = new JPanel(new BorderLayout());
        header.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createMatteBorder(0, 0, 1, 0, rule != null ? rule : Color.LIGHT_GRAY),
                BorderFactory.createEmptyBorder(4, 8, 4, 2)));
        header.add(title, BorderLayout.CENTER);
        header.add(close, BorderLayout.EAST);
        return header;
    }

    /** Width the sidebar opens at; the divider can still be dragged. */
    private static final int OPEN_WIDTH = 320;

    @Override
    public Dimension getPreferredSize() {
        // The old title strip set a 300-pixel minimum width, which was what actually held the
        // sidebar open; the width is now asked for explicitly.
        Dimension d = super.getPreferredSize();
        d.width = Math.max(d.width, OPEN_WIDTH);
        return d;
    }

    public void setTitle(String title) {
        this.title.setText(title);
    }
}
